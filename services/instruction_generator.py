CONDITIONAL_QUALITY_POINTS = {
    (1, 14),
    (2, 6),
    (2, 8),
    (3, 9),
    (5, 9),
}


def is_conditionally_qualified(content, match_start):
    """
    Проверяет, что потенциально запрещённое утверждение находится
    внутри условной формулировки, например:
    "если опасные вещества не применяются...".

    Это нужно, чтобы валидатор не считал корректную условную
    формулировку безусловным утверждением факта.
    """
    content_lower = content.lower()

    # Берём контекст перед найденной фразой. Этого достаточно, чтобы
    # увидеть вводное условие и не пропустить отдельное безусловное
    # утверждение дальше по длинному подпункту.
    context_start = max(0, match_start - 140)
    context = content_lower[context_start:match_start]

    conditional_markers = (
        "если ",
        "если в ",
        "если для ",
        "если такие ",
        "если указанные ",
        "при отсутствии ",
        "в случае отсутствия ",
        "когда такие ",
        "когда указанные ",
    )

    return any(
        marker in context
        for marker in conditional_markers
    )


def find_quality_issues(
    section_text,
    section_number
):
    """
    Проверяет только адресные содержательные ограничения.
    Возвращает список проблем по конкретным подпунктам.

    Для пунктов, где допустима условная формулировка, валидатор
    различает:
    - безусловное утверждение: "опасные вещества не применяются";
    - условное утверждение: "если опасные вещества не применяются...".
    """
    points = extract_points(section_text)
    issues = []

    for point in points:
        if point["section"] != section_number:
            continue

        point_key = (section_number, point["number"])

        rules = QUALITY_RULES.get(
            point_key,
            []
        )

        point_issues = []

        for pattern, message in rules:
            match = re.search(
                pattern,
                point["content"],
                flags=re.IGNORECASE | re.DOTALL
            )

            if not match:
                continue

            if (
                point_key in CONDITIONAL_QUALITY_POINTS
                and is_conditionally_qualified(
                    point["content"],
                    match.start()
                )
            ):
                continue

            point_issues.append(message)

        if point_issues:
            issues.append({
                "section": section_number,
                "number": point["number"],
                "content": point["content"],
                "issues": point_issues
            })

    return issues


def validate_section(
    section_text,
    section_number
):
    expected_order = list(
        SECTION_SETTINGS[
            section_number
        ]["points"].keys()
    )

    expected_numbers = set(expected_order)

    points = extract_points(
        section_text
    )

    section_points = [
        point
        for point in points
        if point["section"] == section_number
    ]

    found_numbers = [
        point["number"]
        for point in section_points
    ]

    found_set = set(found_numbers)

    missing_numbers = sorted(
        expected_numbers - found_set
    )

    unexpected_numbers = sorted(
        found_set - expected_numbers
    )

    duplicate_numbers = sorted({
        number
        for number in found_numbers
        if found_numbers.count(number) > 1
    })

    short_points = []
    errors = []

    if found_numbers != expected_order:
        errors.append(
            "Нарушена последовательность подпунктов. "
            f"Ожидалось: {expected_order}. "
            f"Получено: {found_numbers}."
        )

    if missing_numbers:
        missing_text = ", ".join(
            f"{section_number}.{number}"
            for number in missing_numbers
        )

        errors.append(
            f"Отсутствуют подпункты: "
            f"{missing_text}."
        )

    if unexpected_numbers:
        unexpected_text = ", ".join(
            f"{section_number}.{number}"
            for number in unexpected_numbers
        )

        errors.append(
            f"Обнаружены лишние подпункты: "
            f"{unexpected_text}."
        )

    if duplicate_numbers:
        duplicate_text = ", ".join(
            f"{section_number}.{number}"
            for number in duplicate_numbers
        )

        errors.append(
            f"Дублируются подпункты: "
            f"{duplicate_text}."
        )

    for point in section_points:
        content_length = len(
            point["content"]
        )

        if content_length < MIN_POINT_LENGTH:
            short_points.append({
                "section": point["section"],
                "number": point["number"],
                "content": point["content"],
                "length": content_length
            })

            errors.append(
                f"Подпункт "
                f"{point['section']}."
                f"{point['number']} "
                f"слишком короткий: "
                f"{content_length} символов. "
                f"Нужно не менее {MIN_POINT_LENGTH}."
            )

    quality_points = find_quality_issues(
        section_text,
        section_number
    )

    for quality_point in quality_points:
        point_id = (
            f"{quality_point['section']}."
            f"{quality_point['number']}"
        )

        for issue in quality_point["issues"]:
            errors.append(
                f"Подпункт {point_id}: "
                f"содержательная проверка — {issue}"
            )

    structural_valid = (
        found_numbers == expected_order
        and not missing_numbers
        and not unexpected_numbers
        and not duplicate_numbers
    )

    return {
        "valid": len(errors) == 0,
        "structural_valid": structural_valid,
        "errors": errors,
        "found_numbers": found_numbers,
        "missing_numbers": missing_numbers,
        "unexpected_numbers": unexpected_numbers,
        "duplicate_numbers": duplicate_numbers,
        "short_points": short_points,
        "quality_points": quality_points
    }


def get_point_requirement(
    section_number,
    point_number
):
    """Берет ТЗ конкретного подпункта прямо из SECTION_SETTINGS."""
