def extract_single_generated_point(
    generated_text,
    section_number,
    point_number
):
    """
    Из ответа модели забирает только нужный подпункт и возвращает его
    в нормализованном виде "N.N. текст".
    """
    points = extract_points(generated_text)

    for point in points:
        if (
            point["section"] == section_number
            and point["number"] == point_number
        ):
            return (
                f"{section_number}.{point_number}. "
                f"{point['content'].strip()}"
            )

    point_id = f"{section_number}.{point_number}"

    match = re.search(
        rf"(?ms)^\s*{re.escape(point_id)}\.\s*(.+?)\s*$",
        generated_text
    )

    if match:
        return (
            f"{point_id}. "
            f"{match.group(1).strip()}"
        )

    raise RuntimeError(
        f"YandexGPT вернул подпункт {point_id} "
        f"в нераспознаваемом формате:\n{generated_text}"
    )


def replace_point_in_section(
    section_text,
    section_number,
    point_number,
    new_point_text
):
    """Заменяет один существующий подпункт, не трогая остальные."""
    point_id = f"{section_number}.{point_number}"

    pattern = (
        rf"(?ms)^\s*"
        rf"{re.escape(point_id)}\.\s*"
        rf".*?"
        rf"(?=^\s*\d+\.\d+\.\s|\Z)"
    )

    updated_text, replacements = re.subn(
        pattern,
        new_point_text.strip() + "\n",
        section_text,
        count=1
    )

    if replacements != 1:
        raise RuntimeError(
            f"Не удалось заменить подпункт {point_id}"
        )

    return updated_text.strip()


def repair_one_short_point(
    section_text,
    instruction_name,
    section_number,
    point
):
    point_number = point["number"]
    point_id = f"{section_number}.{point_number}"
    old_text = point["content"]

    for attempt in range(1, MAX_POINT_RETRIES + 1):
        print(
            f"  Исправляю {point_id}: "
            f"попытка {attempt}/{MAX_POINT_RETRIES}"
        )

        generated = regenerate_single_point(
            instruction_name=instruction_name,
            section_number=section_number,
            point_number=point_number,
            old_text=old_text
        )

        normalized = extract_single_generated_point(
            generated,
            section_number,
            point_number
        )

        parsed = extract_points(normalized)

        if not parsed:
            print(
                f"    {point_id}: не удалось разобрать ответ модели"
            )
            old_text = generated
            continue

        content = parsed[0]["content"]
        content_length = len(content)

        if content_length < MIN_POINT_LENGTH:
            print(
                f"    {point_id}: снова короткий — "
                f"{content_length} символов"
            )
            old_text = content
            continue

        print(
            f"    {point_id}: готово — "
            f"{content_length} символов"
        )

        return replace_point_in_section(
            section_text=section_text,
            section_number=section_number,
            point_number=point_number,
            new_point_text=normalized
        )

    raise RuntimeError(
        f"Не удалось увеличить подпункт {point_id} "
        f"до {MIN_POINT_LENGTH} символов"
    )


def repair_short_points(
    section_text,
    instruction_name,
    section_number
):
    """
    Перегенерирует только короткие подпункты.
    Уже корректные подпункты не трогаются.
    """
    validation = validate_section(
        section_text,
        section_number
    )

    if not validation["structural_valid"]:
        raise RuntimeError(
            f"Нельзя точечно исправлять раздел {section_number}: "
            "сначала нужно исправить его структуру"
        )

    short_points = validation["short_points"]

    if not short_points:
        return section_text

    print(
        f"Раздел {section_number}: "
        f"коротких подпунктов — {len(short_points)}. "
        "Исправляю только их."
    )

    for point in short_points:
        section_text = repair_one_short_point(
            section_text=section_text,
            instruction_name=instruction_name,
            section_number=section_number,
            point=point
        )

    return section_text



def repair_one_quality_point(
    section_text,
    instruction_name,
    section_number,
    point
):
    point_number = point["number"]
    point_id = f"{section_number}.{point_number}"
    old_text = point["content"]
    correction_note = " ".join(point["issues"])

    for attempt in range(1, MAX_POINT_RETRIES + 1):
        print(
            f"  Исправляю содержание {point_id}: "
            f"попытка {attempt}/{MAX_POINT_RETRIES}"
        )

        generated = regenerate_single_point(
            instruction_name=instruction_name,
            section_number=section_number,
            point_number=point_number,
            old_text=old_text,
            correction_note=correction_note
        )

        normalized = extract_single_generated_point(
            generated,
            section_number,
            point_number
        )

        parsed = extract_points(normalized)

        if not parsed:
            print(
                f"    {point_id}: не удалось разобрать ответ модели"
            )
            old_text = generated
            continue

        content = parsed[0]["content"]
        content_length = len(content)

        if content_length < MIN_POINT_LENGTH:
            print(
                f"    {point_id}: после исправления короткий — "
                f"{content_length} символов"
            )
            old_text = content
            continue

        test_section = replace_point_in_section(
            section_text=section_text,
            section_number=section_number,
            point_number=point_number,
            new_point_text=normalized
        )

        remaining = [
            issue
            for issue in find_quality_issues(
                test_section,
                section_number
            )
            if issue["number"] == point_number
        ]

        if remaining:
            print(
                f"    {point_id}: содержательная проблема осталась"
            )
            old_text = content
            correction_note = " ".join(
                message
                for issue in remaining
                for message in issue["issues"]
            )
            continue

        print(
            f"    {point_id}: содержание исправлено — "
            f"{content_length} символов"
        )

        return test_section

    print(
        f"  [WARNING] Не удалось полностью исправить "
        f"содержание подпункта {point_id}. "
        "Для beta-версии оставляю предыдущий вариант "
        "и продолжаю генерацию."
    )

    return section_text


def repair_quality_points(
    section_text,
    instruction_name,
    section_number
):
    """
    Исправляет только те подпункты, в которых сработали
    адресные содержательные правила QUALITY_RULES.
    """
    quality_points = find_quality_issues(
        section_text,
        section_number
    )

    if not quality_points:
        return section_text

    print(
        f"Раздел {section_number}: "
        f"содержательных замечаний — {len(quality_points)}. "
        "Исправляю только эти подпункты."
    )

    for point in quality_points:
        for issue in point["issues"]:
            print(
                f"  - {section_number}.{point['number']}: {issue}"
            )

        # После исправления предыдущих пунктов заново берем актуальный
        # текст текущего подпункта из раздела.
        current_points = extract_points(section_text)
        current = next(
            p
            for p in current_points
            if (
                p["section"] == section_number
                and p["number"] == point["number"]
            )
        )

        current_quality = next(
            (
                q
                for q in find_quality_issues(
                    section_text,
                    section_number
                )
                if q["number"] == point["number"]
            ),
            None
        )

        if current_quality is None:
            continue

        current_quality["content"] = current["content"]

        section_text = repair_one_quality_point(
            section_text=section_text,
            instruction_name=instruction_name,
            section_number=section_number,
            point=current_quality
        )

    return section_text



def _extract_json_object(text):
    """Достаёт первый JSON-объект из ответа модели."""
    text = text.strip()

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    match = re.search(r"\{.*\}", text, flags=re.DOTALL)

    if not match:
        raise RuntimeError(
            "Семантический валидатор вернул ответ без JSON:\n"
            + text
        )

    try:
        return json.loads(match.group(0))
    except json.JSONDecodeError as error:
        raise RuntimeError(
            "Не удалось разобрать JSON семантического валидатора:\n"
            + text
        ) from error


