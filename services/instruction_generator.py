def _v6_normalize_context(context):
    """
    Приводит фактический контекст к единому виду.

    Значения:
    - True / False — факт известен;
    - None — факт неизвестен и его нельзя придумывать.
    """
    context = dict(context or {})

    regular_works = context.get("regular_works")
    if not isinstance(regular_works, list):
        regular_works = []

    high_risk_works = context.get("high_risk_works")
    if not isinstance(high_risk_works, list):
        high_risk_works = None

    position_works = context.get("position_works")
    if not isinstance(position_works, list):
        position_works = []

    professional_risks = context.get("professional_risks")
    if not isinstance(professional_risks, list):
        professional_risks = []

    normalized = {
        "source": context.get("source", ""),
        "company_name": context.get("company_name", ""),
        "object_name": context.get("object_name", ""),

        # Работы из опросного листа относятся к организации в целом.
        "regular_works": regular_works,

        # Если эти работы отдельно привязаны именно к должности,
        # их можно передать сюда позднее.
        "position_works": position_works,

        # [] означает: в исходных данных прямо указано отсутствие
        # работ повышенной опасности.
        # None означает: данных нет.
        "high_risk_works": high_risk_works,

        # Следующие факты НЕ выводим из названия должности.
        # Значение должно быть передано явно.
        "shift_work": context.get("shift_work", None),
        "dangerous_substances": context.get(
            "dangerous_substances",
            None
        ),
        "dangerous_waste": context.get(
            "dangerous_waste",
            None
        ),

        # Конкретные риски можно считать известными только если
        # они действительно переданы из ОПР / иных исходных данных.
        "professional_risks": professional_risks,

        # Конкретные СИЗ — только если переданы явно.
        "ppe": context.get("ppe", []),
    }

    return normalized


def _v6_load_questionnaire_context(
    questionnaire_path="input/ОПРОСНЫЙ_ЛИСТ.docx"
):
    """
    Для текущего локального теста автоматически берёт данные из опросного листа.

    Позднее Telegram-слой сможет передавать context напрямую,
    поэтому генератор не будет зависеть от фиксированного имени файла.
    """
    path = _Path(questionnaire_path)

    if not path.exists():
        return {}

    try:
        from services.questionnaire import parse_questionnaire
        data = parse_questionnaire(path)
    except Exception as error:
        print(
            "Предупреждение: не удалось загрузить контекст "
            f"из опросного листа: {error}"
        )
        return {}

    context = dict(data)
    context["source"] = str(path)

    # В нашем парсере high_risk_works=[] соответствует ответу "нет"
    # в загруженном опросном листе.
    if "high_risk_works" not in context:
        context["high_risk_works"] = None

    return context


def _v6_get_context():
    return _v6_normalize_context(
        _V6_CONTEXT.get()
    )


def _v6_bool_fact_text(value):
    if value is True:
        return "ДА — подтверждено исходными данными"
    if value is False:
        return "НЕТ — отсутствие подтверждено исходными данными"
    return "НЕИЗВЕСТНО — запрещено делать вывод"


