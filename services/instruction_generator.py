def _v6_add_issue(issues, point_number, message):
    """
    Добавляет замечание без дублей.
    """
    existing = next(
        (
            item
            for item in issues
            if item["number"] == point_number
        ),
        None
    )

    if existing is None:
        issues.append({
            "number": point_number,
            "issues": [message]
        })
        return

    if message not in existing["issues"]:
        existing["issues"].append(message)


def _v6_point_content(section_text, section_number, point_number):
    for point in extract_points(section_text):
        if (
            point["section"] == section_number
            and point["number"] == point_number
        ):
            return point["content"]

    return ""


def _v6_has_conditional_start(text):
    """
    Общий признак условной формулировки.
    Не пытается понимать весь русский язык, а ловит
    основные допустимые конструкции нашего шаблона.
    """
    lower = text.lower().strip()

    markers = (
        "если ",
        "в случае если ",
        "при наличии ",
        "при отсутствии ",
        "если работодателем ",
        "если условиями ",
        "если в процессе ",
        "если для ",
    )

    return any(
        lower.startswith(marker)
        or f". {marker}" in lower
        for marker in markers
    )


def _v6_fact_rules(section_text, section_number, issues):
    """
    Жёсткие программные правила V6.

    Они не спрашивают AI, "похоже ли это на ошибку".
    Если факта нет в исходных данных, конкретное утверждение
    просто не проходит.
    """
    ctx = _v6_get_context()

    def content(number):
        return _v6_point_content(
            section_text,
            section_number,
            number
        )

    # --------------------------------------------------------------
    # 1.10 — конкретные профессиональные риски только из исходных данных
    # --------------------------------------------------------------
    if section_number == 1 and not ctx["professional_risks"]:
        text = content(10)

        if re.search(
            r"\b(стресс|психоэмоцион\w*|эргономическ\w*\s+фактор\w*|"
            r"эмоциональн\w*\s+нагруз\w*)",
            text,
            flags=re.IGNORECASE
        ):
            _v6_add_issue(
                issues,
                10,
                "Конкретные профессиональные риски не переданы "
                "в исходных данных. Не называй стресс, "
                "психоэмоциональные или эргономические факторы. "
                "Оставь только формулировку о фактически выявленных "
                "условиях труда и результатах оценки профессиональных рисков."
            )

    # --------------------------------------------------------------
    # 1.16 — не придумывать инфекционные/эпидемиологические меры
    # --------------------------------------------------------------
    if section_number == 1:
        text = content(16)

        if re.search(
            r"(инфекцион\w*\s+заболев|распространен\w*\s+инфекц)",
            text,
            flags=re.IGNORECASE
        ):
            _v6_add_issue(
                issues,
                16,
                "Не придумывай цель по предотвращению инфекционных "
                "заболеваний. Оставь только условное требование соблюдать "
                "санитарно-профилактические меры, если они введены."
            )

    # --------------------------------------------------------------
    # 3.2 — не вводить тяжёлые предметы/опасные материалы "на всякий случай"
    # --------------------------------------------------------------
    if section_number == 3:
        text = content(2)

        if re.search(
            r"(тяж[её]л\w*\s+(предмет|груз)|опасн\w*\s+материал)",
            text,
            flags=re.IGNORECASE
        ):
            _v6_add_issue(
                issues,
                2,
                "Не вводи тяжёлые предметы, грузы или опасные материалы, "
                "если они не подтверждены исходными данными. "
                "Оставь безопасное обращение с реально используемыми "
                "документами и предметами труда."
            )

    # --------------------------------------------------------------
    # 3.11 — никаких самостоятельно назначенных режимов температуры
    # --------------------------------------------------------------
    if section_number == 3:
        text = content(11)

        if re.search(
            r"(перерыв\w*.*(обогрев|охлажден)|"
            r"\bобогрев\w*|\bохлажден\w*|"
            r"одева\w*\s+в\s+соответств\w*\s+с\s+(ними|погод))",
            text,
            flags=re.IGNORECASE | re.DOTALL
        ):
            _v6_add_issue(
                issues,
                11,
                "Не устанавливай самостоятельно одежду, специальные "
                "перерывы, обогрев, охлаждение или иной режим труда. "
                "Оставь только учёт погодных условий и меры, "
                "установленные работодателем."
            )

    # --------------------------------------------------------------
    # 3.12 — грамматическая/ролевая ошибка "не требовать от менеджера"
    # --------------------------------------------------------------
    if section_number == 3:
        text = content(12)

        if re.search(
            r"не\s+требова\w*\s+от\s+(менеджер|работник)",
            text,
            flags=re.IGNORECASE
        ):
            _v6_add_issue(
                issues,
                12,
                "Инструкция адресована самому работнику. "
                "Не пиши 'не требовать от менеджера'. "
                "Напиши прямо: работник не проверяет документы, "
                "сертификаты, обучение или охрану труда подрядчиков."
            )

    # --------------------------------------------------------------
    # 4.2 — адресат сообщения без выдуманного ответственного по ОТ
    # --------------------------------------------------------------
    if section_number == 4:
        text = content(2)

        if re.search(
            r"(лиц\w*|работник\w*|специалист\w*)"
            r".{0,40}ответственн\w*.{0,20}охран\w*\s+труд",
            text,
            flags=re.IGNORECASE | re.DOTALL
        ):
            _v6_add_issue(
                issues,
                2,
                "Не назначай без исходных данных лицо, ответственное "
                "за охрану труда. Используй: непосредственный руководитель "
                "или иное установленное работодателем лицо."
            )

    # --------------------------------------------------------------
    # 5.1 и 5.8 — сменность
    # --------------------------------------------------------------
    if section_number == 5 and ctx["shift_work"] is None:
        shift_patterns = (
            r"(как\s+правило|в\s+большинств\w*\s+случа\w*).{0,80}"
            r"(не\s+предполага\w*|не\s+явля\w*).{0,40}(смен|посмен)",
            r"(работ\w*.{0,50})?не\s+предполага\w*.{0,40}(смен|посмен)",
            r"(сменн\w*|посменн\w*).{0,40}(отсутств|неприменим)",
        )

        for number in (1, 8):
            text = content(number)

            if any(
                re.search(
                    pattern,
                    text,
                    flags=re.IGNORECASE | re.DOTALL
                )
                for pattern in shift_patterns
            ):
                _v6_add_issue(
                    issues,
                    number,
                    "Посменный или несменный график не подтверждён "
                    "исходными данными. Не делай вывод по названию должности. "
                    "Сформулируй полностью условно: если работа является "
                    "сменной — передать информацию; если сменность "
                    "не предусмотрена работодателем — специальные "
                    "требования отсутствуют."
                )

    # --------------------------------------------------------------
    # 5.4 — конкретные санитарные процедуры
    # --------------------------------------------------------------
    if section_number == 5:
        text = content(4)

        if re.search(
            r"(мыть\w*\s+рук|мыть[её]\s+рук|"
            r"дезинфицир\w*\s+средств\w*|антисептик)",
            text,
            flags=re.IGNORECASE
        ):
            _v6_add_issue(
                issues,
                4,
                "Не назначай конкретные санитарные процедуры "
                "(мытьё рук с мылом, дезинфицирующие средства и т.п.). "
                "Оставь общую формулировку о личной гигиене "
                "с учётом характера работы."
            )

    # --------------------------------------------------------------
    # 5.9 — опасные отходы
    # --------------------------------------------------------------
    if section_number == 5 and ctx["dangerous_waste"] is None:
        text = content(9)

        # Безусловные конструкции нельзя пропускать.
        # Условная фраза "если ... не образуются" допустима.
        if re.search(
            r"(поскольку|так\s+как).{0,120}"
            r"опасн\w*\s+отход\w*.{0,40}не\s+образ",
            text,
            flags=re.IGNORECASE | re.DOTALL
        ):
            _v6_add_issue(
                issues,
                9,
                "Отсутствие опасных отходов не подтверждено "
                "исходными данными. Используй только условную формулировку: "
                "'если опасные отходы не образуются...'."
            )

        elif (
            re.search(
                r"опасн\w*\s+отход\w*.{0,40}не\s+образ",
                text,
                flags=re.IGNORECASE | re.DOTALL
            )
            and not _v6_has_conditional_start(text)
        ):
            _v6_add_issue(
                issues,
                9,
                "Не утверждай как факт, что опасные отходы не образуются. "
                "Факт неизвестен. Используй условную формулировку."
            )

    # --------------------------------------------------------------
    # 5.11 — не превращать сотрудника в хозяйственный персонал
    # --------------------------------------------------------------
    if section_number == 5:
        text = content(11)

        if re.search(
            r"(убира\w*\s+за\s+собой\s+мусор|"
            r"мыть[её]\s+помещен|"
            r"моющ\w*\s+средств|"
            r"контрол\w*.{0,30}(вентиляц|кондиционир|кухн|сануз))",
            text,
            flags=re.IGNORECASE | re.DOTALL
        ):
            _v6_add_issue(
                issues,
                11,
                "Не перечисляй конкретные хозяйственные работы "
                "(уборка мусора, мытьё помещений, моющие средства, "
                "контроль вентиляции и т.п.). Оставь только обязанность "
                "содержать собственное рабочее место в надлежащем "
                "санитарно-гигиеническом состоянии в пределах своих обязанностей."
            )

    # --------------------------------------------------------------
    # Неизвестные опасные вещества: запрещаем безусловное отсутствие
    # в ключевых условных пунктах.
    # --------------------------------------------------------------
    if ctx["dangerous_substances"] is None:
        for sec, number in (
            (1, 14),
            (2, 6),
            (3, 9),
        ):
            if section_number != sec:
                continue

            text = content(number)

            unconditional = re.search(
                r"(поскольку|так\s+как).{0,140}"
                r"(не\s+(работа\w*|контактир\w*|применя\w*|использ\w*)"
                r".{0,50}опасн\w*\s+веществ|"
                r"опасн\w*\s+веществ\w*.{0,50}не\s+(применя\w*|использ\w*))",
                text,
                flags=re.IGNORECASE | re.DOTALL
            )

            if unconditional:
                _v6_add_issue(
                    issues,
                    number,
                    "Наличие или отсутствие опасных веществ "
                    "не подтверждено исходными данными. "
                    "Используй только условную формулировку 'если ...'."
                )

    # V5 ожидает, что каждое замечание содержит ключ section.
    # V6 добавляет собственные замечания через _v6_add_issue(),
    # поэтому гарантируем единый формат перед возвратом.
    for item in issues:
        item.setdefault("section", section_number)

    return issues


def find_quality_issues(
    section_text,
    section_number
):
    """
    V6 = адресные правила V5 + детерминированный факт-чекер.
    """
    issues = _v5_find_quality_issues(
        section_text,
        section_number
    )

    return _v6_fact_rules(
        section_text,
        section_number,
        issues
    )


def generate_instruction(instruction_name, context=None):
    context_token = _V6_CONTEXT.set(context or {})
    position_token = set_current_position(instruction_name)

    try:
        sections = []

        for section_number in range(1, 6):
            section_text = generate_valid_section(
                instruction_name,
                section_number
            )

            sections.append(section_text)

        result = "\n\n".join(sections)

        validation = validate_instruction(result)

        if not validation["valid"]:
            print()
            print("Итоговая проверка не пройдена:")

            for error in validation["errors"]:
                print(f"  - {error}")

            raise RuntimeError(
                "Итоговая инструкция не прошла проверку"
            )

        return result
    finally:
        reset_current_position(position_token)
        _V6_CONTEXT.reset(context_token)

